# Интерпретация общего результата в процентах. Формат: (lo, hi, текст).
RESULT_LEVELS = [
    (100, 100, "Отлично — участок полностью соответствует 5С. Так держать! ✅"),
    (70, 99, "Хорошо — сделан большой объём работы, есть что докрутить. 🙂"),
    (50, 69, "Средне — работа проделана частично. Разберите невыполненные пункты. 😕"),
    (20, 49, "Начальная стадия — много невыполненных пунктов. ⚠️"),
    (0, 19, "Участок пока не соответствует 5С. Начните с шага «Сортировка». 🚩"),
]


def interpret_total(percent: int) -> str:
    for lo, hi, text in RESULT_LEVELS:
        if lo <= percent <= hi:
            return text
    return RESULT_LEVELS[-1][2]
